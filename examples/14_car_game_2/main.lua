-- --------------------------------------------------------------- world ------
local function build_world()
    P.createPlane(0, 0, 0, 0, 1, 0, 800)

    -- Scattered cargo crates near the start so you have something to hit.
    for _, s in ipairs({
        { -6, 0.5,  18 }, { -3, 0.5,  18 }, { 0, 0.5, 18 }, { 3, 0.5, 18 }, { 6, 0.5, 18 },
        { -6, 0.5,  26 }, { -3, 0.5,  26 }, { 0, 0.5, 26 }, { 3, 0.5, 26 }, { 6, 0.5, 26 },
    }) do
        crates[#crates + 1] = P.createBox(s[1], s[2], s[3], 0.5, 0.5, 0.5, "dynamic", 0.7, 0.15, 300)
    end
end

-- ------------------------------------------------------------- vehicles -----
local function tractor_wheels()
    local fd = (layout == "FWD" or layout == "AWD")
    local rd = (layout == "RWD" or layout == "AWD")
    local function w(sx, z, front, drive, spring, damp, brake, hbrake)
        return {
            pos                   = { sx * TRACTOR.x, TRACTOR.y, z },
            radius                = TRACTOR.wheel_radius,
            width                 = TRACTOR.wheel_width,
            suspensionMinLength   = 0.10,
            suspensionMaxLength   = 0.40,
            suspensionSpring      = spring,
            suspensionDamping     = damp,
            maxSteerAngleRad      = front and TRACTOR.steer or 0.0,
            maxBrakeTorque        = brake,
            maxHandBrakeTorque    = hbrake,
            isFront               = front,
            isDrive               = drive,
        }
    end
    return {
        w( 1, TRACTOR.front_z, true,  fd, TRACTOR.spring_f, TRACTOR.damp_f, TRACTOR.brake_f, 0),
        w(-1, TRACTOR.front_z, true,  fd, TRACTOR.spring_f, TRACTOR.damp_f, TRACTOR.brake_f, 0),
        w( 1, TRACTOR.rear_z,  false, rd, TRACTOR.spring_r, TRACTOR.damp_r, TRACTOR.brake_r, TRACTOR.hbrake_r),
        w(-1, TRACTOR.rear_z,  false, rd, TRACTOR.spring_r, TRACTOR.damp_r, TRACTOR.brake_r, TRACTOR.hbrake_r),
    }
end

local function trailer_wheels()
    local list = {}
    -- Rear tandem: 4 wheels
    for _, z in ipairs(TRAILER.rear_z) do
        for _, sx in ipairs({ 1, -1 }) do
            list[#list + 1] = {
                pos = { sx * TRAILER.x, TRAILER.rear_y, z },
                radius = TRAILER.wheel_radius, width = TRAILER.wheel_width,
                suspensionMinLength = 0.10, suspensionMaxLength = 0.35,
                suspensionSpring = TRAILER.spring_r, suspensionDamping = TRAILER.damp_r,
                maxSteerAngleRad = 0, maxBrakeTorque = 2500, maxHandBrakeTorque = 8000,
                isFront = false, isDrive = false,
            }
        end
    end
    -- Landing gear legs (wheels, so they roll when they touch)
    for _, sx in ipairs({ 1, -1 }) do
        list[#list + 1] = {
            pos = { sx * 0.90, TRAILER.landing_y, TRAILER.landing_z },
            radius = TRAILER.wheel_radius, width = TRAILER.wheel_width,
            suspensionMinLength = 0.02, suspensionMaxLength = 0.10,
            suspensionSpring = TRAILER.spring_l, suspensionDamping = TRAILER.damp_l,
            maxSteerAngleRad = 0, maxBrakeTorque = 0, maxHandBrakeTorque = 0,
            isFront = false, isDrive = false,
        }
    end
    return list
end

local function spawn_tractor()
    local s = TRACTOR.spawn
    tractor_body = P.createBox(s.x, s.y, s.z,
        TRACTOR.half[1], TRACTOR.half[2], TRACTOR.half[3],
        "dynamic", 0.6, 0.1, TRACTOR.density)
    tractor_body:setDamping(0.02, 0.55)
    tractor_body:setMotionQuality(true)

    local ok, v = pcall(P.createWheeledVehicle, {
        chassis = tractor_body,
        wheels  = tractor_wheels(),
        maxPitchRollAngle = math.rad(70),

        engineMaxTorque = 2400, engineMinRpm = 500, engineMaxRpm = 2100,
        engineInertia   = 3.0,
        torqueCurve = { {0.0, 0.90}, {0.20, 1.00}, {0.55, 0.95}, {0.80, 0.75}, {1.0, 0.50} },

        transmission = manual and "manual" or "auto",
        gearRatios   = { 7.0, 4.0, 2.4, 1.6, 1.15, 0.90 },
        reverseGearRatios = { 6.0 },
        shiftUpRpm = 1800, shiftDownRpm = 800, clutchStrength = 45,

        differentialRatio      = 4.5,
        limitedSlipRatio       = 2.0,
        centerLimitedSlipRatio = 2.0,
        frontTorqueSplit       = 0.25,

        antiRollFront = 20000,
        antiRollRear  = 30000,
        collisionTester = "ray",
    })
    if not ok then err_msg = tostring(v); return nil end
    if manual then v:setGear(1, 1.0) end
    return v
end

local function spawn_trailer()
    local s = TRAILER.spawn
    trailer_body = P.createBox(s.x, s.y, s.z,
        TRAILER.half[1], TRAILER.half[2], TRAILER.half[3],
        "dynamic", 0.7, 0.05, TRAILER.density)
    trailer_body:setDamping(0.02, 0.40)
    trailer_body:setMotionQuality(true)

    local ok, v = pcall(P.createWheeledVehicle, {
        chassis = trailer_body,
        wheels  = trailer_wheels(),
        maxPitchRollAngle = math.rad(80),
        engineMaxTorque = 0, engineMinRpm = 0, engineMaxRpm = 1,
        transmission = "manual",
        antiRollFront = 0,
        antiRollRear  = 8000,
        collisionTester = "ray",
    })
    if not ok then err_msg = tostring(v); return nil end
    return v
end

-- --------------------------------------------------------------- hitch ------
local function fifth_wheel_world()
    if not (tractor_body and tractor_body:isValid()) then return nil end
    local tx, ty, tz = tractor_body:getPosition()
    local qx, qy, qz, qw = tractor_body:getQuaternion()
    local fw = TRACTOR.fifth_wheel_local
    local dx, dy, dz = rotate_vec3(fw[1], fw[2], fw[3], qx, qy, qz, qw)
    return tx + dx, ty + dy, tz + dz
end

local function kingpin_world()
    if not (trailer_body and trailer_body:isValid()) then return nil end
    local tx, ty, tz = trailer_body:getPosition()
    local qx, qy, qz, qw = trailer_body:getQuaternion()
    local kp = TRAILER.kingpin_local
    local dx, dy, dz = rotate_vec3(kp[1], kp[2], kp[3], qx, qy, qz, qw)
    return tx + dx, ty + dy, tz + dz
end

local function attach_trailer()
    if hitch then hitch:destroy(); hitch = nil end
    if not (tractor_body and tractor_body:isValid()) then return false end
    if not (trailer_body and trailer_body:isValid()) then return false end

    local tx, ty, tz = tractor_body:getPosition()
    local tqx, tqy, tqz, tqw = tractor_body:getQuaternion()

    -- Target world position of the tractor's fifth wheel.
    local fx, fy, fz = fifth_wheel_world()

    -- Where is the trailer's kingpin right now?
    local kx, ky, kz = kingpin_world()
    local dx, dy, dz = fx - kx, fy - ky, fz - kz
    local dist = sqrt(dx*dx + dy*dy + dz*dz)

    -- If we're not reasonably close, refuse (like a real truck sim).
    if dist > 4.0 then
        return false
    end

    -- Snap the trailer so the kingpin sits exactly at the fifth wheel,
    -- keeping the trailer's current orientation.
    local px, py, pz = trailer_body:getPosition()
    trailer_body:setPosition(px + dx, py + dy, pz + dz, true)

    -- Create the hinge at the fifth wheel: world vertical axis.
    hitch = P.createHingeConstraint(tractor_body, trailer_body, fx, fy, fz, 0, 1, 0)
    return true
end

local function detach_trailer()
    if hitch then
        hitch:destroy()
        hitch = nil
    end
end

-- --------------------------------------------------------------- lifecycle --
local function reset_all()
    if hitch then hitch:destroy(); hitch = nil end
    P.destroyAll()
    crates = {}
    skids  = {}
    skid_last = {}

    P.setGravity(0, -9.81, 0)
    build_world()
    tractor = spawn_tractor()
    trailer = spawn_trailer()
    attach_trailer()

    cam.heading = 0
    orbit.yaw = 0
    orbit.pitch = orbit.default_pitch
    orbit.idle = 0
end

