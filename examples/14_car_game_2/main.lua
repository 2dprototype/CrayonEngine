-- --------------------------------------------------------------- driving ----
local function update_driver(dt)
    if not (tractor and tractor:isValid()) then return end

    local up    = K.isDown("w") or K.isDown("up")
    local down  = K.isDown("s") or K.isDown("down")
    local left  = K.isDown("a") or K.isDown("left")
    local right = K.isDown("d") or K.isDown("right")
    local hbrake = K.isDown("space") and 1.0 or 0.0

    local fwd_speed = tractor:getForwardSpeed()
    local speed_kmh = tractor:getSpeedKmh()

    local throttle, brake = 0.0, 0.0
    if manual then
        throttle = up   and 1.0 or 0.0
        brake    = down and 1.0 or 0.0
    else
        if up then
            if fwd_speed < -1.0 then brake = 1.0 else throttle = 1.0 end
        end
        if down then
            if fwd_speed > 1.0 then brake = 1.0; throttle = 0.0
            else throttle = -1.0 end
        end
    end

    -- Steering: trucks steer slowly.  Rate narrows with speed.
    local target = (right and 1 or 0) - (left and 1 or 0)
    local speed_factor = 1.0 / (1.0 + (speed_kmh / 40.0) ^ 2)
    local rate = (target == 0) and 4.0 or 2.5
    steer_input = steer_input + (target * speed_factor - steer_input) * min(1.0, rate * dt)

    tractor:setInputWheeled(throttle, steer_input, brake, hbrake)

    if manual then
        local gear = tractor:getTransmissionGear()
        if K.isPressed("e") then tractor:setGear(min(gear + 1, 6), 1.0) end
        if K.isPressed("q") then tractor:setGear(max(gear - 1, -1), 1.0) end
    end

    -- Rolling resistance on the tractor.
    local vx, vy, vz = tractor_body:getVelocity()
    local speed = sqrt(vx*vx + vy*vy + vz*vz)
    local drag = 0.35 * speed * dt
    tractor_body:applyImpulse(-vx * drag, -vy * drag * 0.2, -vz * drag)

    -- Turbo
    if K.isDown("lshift") and turbo > 0 and throttle > 0 then
        local qx, qy, qz, qw = tractor_body:getQuaternion()
        local fx, fy, fz = quat_forward(qx, qy, qz, qw)
        local f = 40000 * dt
        tractor_body:applyImpulse(fx * f, fy * f, fz * f)
        turbo = max(0, turbo - 20 * dt)
    else
        turbo = min(100, turbo + 4 * dt)
    end
end

-- ------------------------------------------------------------- mouse look ---
local function update_mouse_look(dt)
    local dx, dy = M.getDelta()

    local _, wdy = M.getWheel()
    if wdy and abs(wdy) > 0.001 then
        orbit.dist = clamp(orbit.dist - wdy * 0.7, 8.0, 32.0)
    end

    if dx and dy and (abs(dx) > 0.001 or abs(dy) > 0.001) then
        orbit.yaw   = orbit.yaw - dx * orbit.sens
        orbit.pitch = clamp(orbit.pitch - dy * orbit.sens, orbit.pitch_min, orbit.pitch_max)
        orbit.idle  = 0
    else
        orbit.idle = orbit.idle + dt
    end

    if orbit.idle > orbit.recenter_delay_yaw then
        local kmh = tractor and tractor:getSpeedKmh() or 0
        if kmh > 4 then
            if orbit.yaw >  pi then orbit.yaw = orbit.yaw - 2*pi end
            if orbit.yaw < -pi then orbit.yaw = orbit.yaw + 2*pi end
            local rate = orbit.recenter_base_rate
                + (orbit.recenter_max_rate - orbit.recenter_base_rate) * min(kmh / 40.0, 1.0)
            orbit.yaw = orbit.yaw * exp(-rate * dt)
        end
    end
    if orbit.idle > orbit.recenter_delay_pitch then
        orbit.pitch = orbit.pitch + (orbit.default_pitch - orbit.pitch) * min(1.0, dt * 1.4)
    end
end

-- ------------------------------------------------------------- skid marks ---
local skid_parity = 0
local function update_skids()
    if not (tractor and tractor:isValid()) then return end
    skid_parity = 1 - skid_parity
    if skid_parity ~= 0 then return end

    for i = 1, 4 do
        local info = tractor:getWheelInfo(i - 1)
        if info and info.contact and info.skid > 0.55 then
            local p = info.contactPos
            local last = skid_last[i]
            local cur = { p.x, p.y + 0.02, p.z }
            if last then
                local ddx, ddz = cur[1] - last[1], cur[3] - last[3]
                local d = sqrt(ddx*ddx + ddz*ddz)
                if d > 0.35 and d < 5.0 then
                    local lx, lz = -ddz / d * 0.16, ddx / d * 0.16
                    skids[#skids + 1] = {
                        {last[1] + lx, last[2], last[3] + lz},
                        {last[1] - lx, last[2], last[3] - lz},
                        {cur[1] - lx, cur[2], cur[3] - lz},
                        {cur[1] + lx, cur[2], cur[3] + lz},
                    }
                    if #skids > 80 then table.remove(skids, 1) end
                    skid_last[i] = cur
                elseif d >= 5.0 then
                    skid_last[i] = cur
                end
            else
                skid_last[i] = cur
            end
        else
            skid_last[i] = nil
        end
    end
end

-- ------------------------------------------------------------- main update --
function crayon.update(dt)
    dt = min(dt, 0.05)
    cached_dt = dt

    if K.isPressed("escape") then crayon.window.quit() end

    -- Hitch toggle
    if K.isPressed("l") then
        if hitch then
            detach_trailer()
        else
            attach_trailer()
        end
    end

    if K.isPressed("1") then layout = "RWD"; if tractor then tractor:destroy() end; tractor = spawn_tractor(); if hitch then attach_trailer() end end
    if K.isPressed("2") then layout = "FWD"; if tractor then tractor:destroy() end; tractor = spawn_tractor(); if hitch then attach_trailer() end end
    if K.isPressed("3") then layout = "AWD"; if tractor then tractor:destroy() end; tractor = spawn_tractor(); if hitch then attach_trailer() end end

    if K.isPressed("t") then
        manual = not manual
        if tractor then
            tractor:setManualTransmission(manual)
            if manual then tractor:setGear(1, 1.0) end
        end
    end
    if K.isPressed("c") then
        cam_mode = cam_mode % 4 + 1
        if     cam_mode == 1 then orbit.dist = 14.0
        elseif cam_mode == 2 then orbit.dist = 24.0
        elseif cam_mode == 4 then orbit.dist = 28.0 end
    end
    if K.isPressed("h")  then show_help = not show_help end
    if K.isPressed("f1") then show_telemetry = not show_telemetry end
    if K.isPressed("f2") then show_debug = not show_debug end
    if K.isPressed("r")  then reset_all() end

    update_driver(dt)
    update_mouse_look(dt)
    update_skids()
end

-- ------------------------------------------------------------------ camera --
local function update_camera()
    if not (tractor_body and tractor_body:isValid()) then return end

    -- Camera aims at a point roughly 1/3 back along the tractor+trailer rig.
    local px, py, pz = tractor_body:getPosition()
    local qx, qy, qz, qw = tractor_body:getQuaternion()
    local fx, fy, fz = quat_forward(qx, qy, qz, qw)
    local car_heading = atan2(fx, fz)

    cam.heading = angle_lerp(cam.heading, car_heading, min(1, cached_dt * 4.0))

    local speed = tractor and tractor:getSpeedKmh() or 0
    local fov_target = 62 + clamp(speed * 0.10, 0, 15)
    cam_tbl.fov = lerp(cam_tbl.fov, fov_target, min(1, cached_dt * 3))

    local pos, target = cam_tbl.position, cam_tbl.target
    local h = cam.heading + orbit.yaw
    local hx, hz = sin(h), cos(h)
    local cos_p, sin_p = cos(orbit.pitch), sin(orbit.pitch)

    local horiz = orbit.dist * cos_p
    local vert  = orbit.dist * sin_p

    pos[1] = px - hx * horiz
    pos[2] = max(py + 2.6 + vert, 1.2)
    pos[3] = pz - hz * horiz

    target[1] = px + hx * 4.0
    target[2] = py + 1.2
    target[3] = pz + hz * 4.0

    G.setCamera3D(cam_tbl)
end

-- -------------------------------------------------------------------- draw -
local function draw_world()
    G.setColor(1, 1, 1, 1)
    G.drawPlane(0, 0, 0, 500, 500, textures.ground)

    for _, b in ipairs(crates) do
        if b:isValid() then
            local x, y, z = b:getPosition()
            local qx, qy, qz, qw = b:getQuaternion()
            G.setColor(1, 1, 1, 1)
            draw_with_pose(x, y, z, qx, qy, qz, qw, function()
                G.drawModel(models.crate, 0, 0, 0, 0, 0, 0, 1, 1, 1)
            end)
        end
    end

    G.setColor(0.04, 0.04, 0.05, 1)
    for _, q in ipairs(skids) do
        G.drawQuad3D(q[1], q[2], q[3], q[4])
        G.drawQuad3D(q[4], q[3], q[2], q[1])
    end
end

local function draw_vehicle_pair()
    if tractor_body and tractor_body:isValid() then
        local x, y, z = tractor_body:getPosition()
        local qx, qy, qz, qw = tractor_body:getQuaternion()
        G.setColor(1, 1, 1, 1)
        draw_with_pose(x, y, z, qx, qy, qz, qw, function()
            G.drawModel(models.tractor, 0, 0, 0, 0, 0, 0, 1, 1, 1)
        end)

        if tractor and tractor:isValid() then
            for i = 0, tractor:getWheelCount() - 1 do
                local t = tractor:getWheelTransform(i)
                if t then
                    local r = t.rotation
                    draw_with_pose(t.position.x, t.position.y, t.position.z,
                                   r.x, r.y, r.z, r.w,
                        function() G.drawModel(models.wheel, 0, 0, 0, 0, 0, 0, 1, 1, 1) end)
                end
            end
        end
    end

    if trailer_body and trailer_body:isValid() then
        local x, y, z = trailer_body:getPosition()
        local qx, qy, qz, qw = trailer_body:getQuaternion()
        G.setColor(1, 1, 1, 1)
        draw_with_pose(x, y, z, qx, qy, qz, qw, function()
            G.drawModel(models.trailer, 0, 0, 0, 0, 0, 0, 1, 1, 1)
        end)

        if trailer and trailer:isValid() then
            for i = 0, trailer:getWheelCount() - 1 do
                local t = trailer:getWheelTransform(i)
                if t then
                    local r = t.rotation
                    draw_with_pose(t.position.x, t.position.y, t.position.z,
                                   r.x, r.y, r.z, r.w,
                        function() G.drawModel(models.wheel, 0, 0, 0, 0, 0, 0, 1, 1, 1) end)
                end
            end
        end
    end
end

local function bar(x, y, w, h, frac, r, g, b)
    G.setColor(0, 0, 0, 0.55); G.drawRect("fill", x - 2, y - 2, w + 4, h + 4)
    G.setColor(r, g, b, 1);    G.drawRect("fill", x, y, w * clamp(frac, 0, 1), h)
end

local function draw_hud()
    local W, H = cached_w, cached_h

    if not (tractor and tractor:isValid()) then
        G.setColor(1, 0.3, 0.3, 1)
        G.drawText("Truck failed to build: " .. tostring(err_msg), 20, 20)
        return
    end

    local speed = tractor:getSpeedKmh()
    local rpm   = tractor:getEngineRpm()
    local gear  = tractor:getTransmissionGear()
    local gtxt  = gear < 0 and "R" or (gear == 0 and "N" or tostring(gear))

    G.setColor(1, 1, 1, 1)
    G.drawText(format("%3d", speed), 24, H - 90, { scale = 2.4 })
    G.drawText("km/h", 116, H - 56, { scale = 1.1 })
    G.drawText(gtxt, 160, H - 96, { scale = 2.4 })

    bar(24, H - 24, 200, 8, rpm / 2100,
        rpm > 1800 and 1 or 0.2, rpm > 1800 and 0.2 or 0.85, 0.2)
    bar(24, H - 38, 100, 5, turbo / 100, 0.2, 0.6, 1.0)

    G.setColor(0.9, 0.9, 1, 1)
    G.drawText(format("%s | %s", layout, manual and "MAN" or "AUTO"), 24, 20)

    -- Hitch indicator (bright when attached)
    if hitch then
        G.setColor(0.3, 1.0, 0.4, 1)
        G.drawText("HITCH: ATTACHED", 24, 36)
    else
        G.setColor(1.0, 0.5, 0.2, 1)
        G.drawText("HITCH: DETACHED  (press L near trailer)", 24, 36)
    end

    if show_telemetry then
        G.setColor(0, 0, 0, 0.55); G.drawRect("fill", W - 330, 70, 316, 100)
        G.setColor(1, 1, 1, 1)
        local names = { "FL", "FR", "RL", "RR" }
        for i = 1, 4 do
            local w = tractor:getWheelInfo(i - 1)
            if w then
                G.drawText(format("%s %s susp %.2f  slip %+.2f/%+.2f",
                    names[i], w.contact and "GND" or "AIR",
                    w.suspension, w.longSlip, w.latSlip), W - 322, 78 + (i - 1) * 16)
            end
        end
        G.drawText(format("fwd %.1f m/s", tractor:getForwardSpeed()), W - 322, 148)
    end

    if show_help then
        G.setColor(0, 0, 0, 0.55); G.drawRect("fill", 14, 56, 300, 144)
        G.setColor(0.95, 0.95, 0.95, 1)
        local lines = {
            "W/S throttle+brake  A/D steer",
            "SPACE trailer brake  L hitch on/off",
            "MOUSE look  WHEEL zoom  LSHIFT turbo",
            "C camera  T auto/manual (Q/E shift)",
            "1/2/3 RWD/FWD/AWD",
            "R reset  F1 telemetry  F2 debug  H hide",
        }
        for i, l in ipairs(lines) do G.drawText(l, 22, 64 + (i - 1) * 16) end
    end
end

function crayon.draw()
    G.clear(0.55, 0.72, 0.92, 1)
    update_camera()
    if not show_debug then
        draw_world()
        draw_vehicle_pair()
    end
    if show_debug then P.drawDebug({ vehicles = true, shapes = true, constraints = true }) end
    draw_hud()
end