#!/usr/bin/env python3
"""Embeds src/scripting/prelude/*.lua into src/scripting/lua_prelude_data.cpp.
Run after editing any prelude file:   python3 tools/embed_lua.py
(Chunks are split into <4 KB string pieces so MSVC's string-literal limits are never hit.)"""
import glob, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = sorted(glob.glob(os.path.join(root, "src/scripting/prelude/*.lua")))

def c_literal(line):
    out = []
    for b in line.encode("utf-8"):
        c = chr(b)
        if c == "\\": out.append("\\\\")
        elif c == '"': out.append('\\"')
        elif c == "\n": out.append("\\n")
        elif c == "\r": out.append("\\r")
        elif c == "\t": out.append("\\t")
        elif 32 <= b < 127 and c != "?": out.append(c)
        else: out.append("\\%03o" % b)       # octal escapes (3 digits) are unambiguous
    return '"' + "".join(out) + '"'

lines = ["// GENERATED by tools/embed_lua.py from src/scripting/prelude/*.lua -- do not edit.",
         '#include "lua_prelude.hpp"', "", "namespace crayon {", ""]
names = []
for idx, path in enumerate(files):
    name = os.path.basename(path)
    text = open(path, encoding="utf-8").read()
    names.append((name, idx))
    lines.append("static const char* const kPieces%d[] = {" % idx)
    piece, size = [], 0
    src_lines = text.splitlines(keepends=True)
    for ln in src_lines:
        lit = c_literal(ln)
        piece.append(lit); size += len(ln)
        if size > 3500:
            lines.append("    " + "\n    ".join(piece) + ",")
            piece, size = [], 0
    if piece:
        lines.append("    " + "\n    ".join(piece) + ",")
    lines.append("    nullptr};")
    lines.append("")
lines.append("extern const PreludeChunk kPreludeChunks[] = {")
for name, idx in names:
    lines.append('    {"%s", kPieces%d},' % (name, idx))
lines.append("    {nullptr, nullptr}};")
lines.append("")
lines.append("} // namespace crayon")
out = os.path.join(root, "src/scripting/lua_prelude_data.cpp")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote %s (%d files)" % (os.path.relpath(out, root), len(files)))
